/** Any interface string the app shows. */
export type TKey = keyof typeof FR;
type Vars = Record<string, string | number>;

const BIN_FR: Record<BinKey, string> = { recycling: 'Recyclage', compost: 'Compost', garbage: 'Ordures', special: 'Spécial' };

/** Translate outside React (e.g. in a callback that already has `lang`). */
export function translate(lang: 'fr' | 'en', key: TKey, vars?: Vars): string {
  const s: string = lang === 'fr' ? FR[key] : key;
  return vars ? s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? '')) : s;
}

/** `t('Save all {n} items', { n })` and `binLabel('compost')` in the player's language. */
export function useT() {
  const { lang } = useApp();
  const t = useCallback((key: TKey, vars?: Vars) => translate(lang, key, vars), [lang]);
  const binLabel = useCallback((b: BinKey) => (lang === 'fr' ? BIN_FR[b] : bins[b].label), [lang]);
  return { t, binLabel, lang };
}
